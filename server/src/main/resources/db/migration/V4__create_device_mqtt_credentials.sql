CREATE TABLE device_mqtt_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    username VARCHAR(128) NOT NULL,
    password_hash VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    last_used_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_device_mqtt_credentials_device_id
        UNIQUE (device_id),
    CONSTRAINT uq_device_mqtt_credentials_username
        UNIQUE (username),
    CONSTRAINT fk_device_mqtt_credentials_device_id
        FOREIGN KEY (device_id) REFERENCES devices ON DELETE CASCADE,
    CONSTRAINT chk_device_mqtt_credentials_status
        CHECK (status IN ('ACTIVE', 'REVOKED'))
);
