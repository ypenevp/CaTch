ALTER TABLE users
    DROP CONSTRAINT users_role_check;

ALTER TABLE users
    ADD CONSTRAINT users_role_check
        CHECK (role IN ('USER', 'ADMIN', 'FACTORY', 'RELATIVE'));

CREATE TABLE user_relatives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    relative_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_user_relatives_user_relative
        UNIQUE (user_id, relative_id),
    CONSTRAINT fk_user_relatives_user_id
        FOREIGN KEY (user_id) REFERENCES users ON DELETE CASCADE,
    CONSTRAINT fk_user_relatives_relative_id
        FOREIGN KEY (relative_id) REFERENCES users ON DELETE CASCADE
);

CREATE INDEX idx_user_relatives_relative_id ON user_relatives (relative_id);
