CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL,
    ai_analysis_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    title VARCHAR(128) NOT NULL,
    message VARCHAR(512) NOT NULL,
    fall_probability DOUBLE PRECISION,
    detected_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP(6) WITH TIME ZONE,
    email_status VARCHAR(32) NOT NULL,
    push_status VARCHAR(32) NOT NULL,
    realtime_status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notifications_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_device
        FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_ai_analysis
        FOREIGN KEY (ai_analysis_id) REFERENCES ai_analyses(id) ON DELETE CASCADE,
    CONSTRAINT uq_notifications_recipient_analysis
        UNIQUE (recipient_user_id, ai_analysis_id),
    CONSTRAINT chk_notifications_type
        CHECK (type IN ('FALL_DETECTED')),
    CONSTRAINT chk_notifications_email_status
        CHECK (email_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    CONSTRAINT chk_notifications_push_status
        CHECK (push_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    CONSTRAINT chk_notifications_realtime_status
        CHECK (realtime_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED'))
);

CREATE INDEX idx_notifications_recipient_created
    ON notifications(recipient_user_id, created_at DESC);

CREATE INDEX idx_notifications_recipient_unread
    ON notifications(recipient_user_id, read_at, created_at DESC);

CREATE TABLE user_push_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token VARCHAR(512) NOT NULL,
    platform VARCHAR(32) NOT NULL,
    device_name VARCHAR(128),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_push_tokens_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_user_push_tokens_token
        UNIQUE (token),
    CONSTRAINT chk_user_push_tokens_platform
        CHECK (platform IN ('ANDROID', 'IOS', 'WEB'))
);

CREATE INDEX idx_user_push_tokens_user_active
    ON user_push_tokens(user_id, active);
