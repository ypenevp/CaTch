CREATE TABLE ai_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    activity VARCHAR(64) NOT NULL,
    fall_detected BOOLEAN NOT NULL,
    fall_probability DOUBLE PRECISION NOT NULL,
    fall_cause VARCHAR(64),
    fall_reason VARCHAR(255),
    heart_rate INTEGER,
    window_start_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    window_end_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_measurement_id BIGINT NOT NULL,
    analyzed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ai_analyses_device_id
        FOREIGN KEY (device_id) REFERENCES devices ON DELETE CASCADE
);

CREATE INDEX idx_ai_analyses_device_id
    ON ai_analyses (device_id, id DESC);

CREATE INDEX idx_ai_analyses_device_falls
    ON ai_analyses (device_id, id DESC)
    WHERE fall_detected;
