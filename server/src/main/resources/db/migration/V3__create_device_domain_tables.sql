CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    owner_id BIGINT,
    claim_secret_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    claimed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_devices_device_id UNIQUE (device_id),
    CONSTRAINT uq_devices_claim_secret_hash UNIQUE (claim_secret_hash),
    CONSTRAINT fk_devices_owner_id
        FOREIGN KEY (owner_id) REFERENCES users,
    CONSTRAINT chk_devices_status
        CHECK (status IN ('UNCLAIMED', 'ACTIVE'))
);

CREATE TABLE device_pairings (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL,
    pairing_token_hash VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paired_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_device_pairings_token_hash
        UNIQUE (pairing_token_hash),
    CONSTRAINT fk_device_pairings_user_id
        FOREIGN KEY (user_id) REFERENCES users,
    CONSTRAINT fk_device_pairings_device_id
        FOREIGN KEY (device_id) REFERENCES devices,
    CONSTRAINT chk_device_pairings_status
        CHECK (status IN ('PENDING', 'PAIRED', 'EXPIRED', 'CANCELLED'))
);

CREATE TABLE device_measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    measured_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    accel_x DOUBLE PRECISION,
    accel_y DOUBLE PRECISION,
    accel_z DOUBLE PRECISION,
    gyro_x DOUBLE PRECISION,
    gyro_y DOUBLE PRECISION,
    gyro_z DOUBLE PRECISION,
    heart_rate INTEGER,
    spo2 DOUBLE PRECISION,
    CONSTRAINT uq_device_measurements_device_measured_at
        UNIQUE (device_id, measured_at),
    CONSTRAINT fk_device_measurements_device_id
        FOREIGN KEY (device_id) REFERENCES devices ON DELETE CASCADE
);

CREATE INDEX idx_device_measurements_device_measured_at
    ON device_measurements (device_id, measured_at DESC);

CREATE INDEX idx_device_measurements_device_received_at
    ON device_measurements (device_id, received_at DESC);
